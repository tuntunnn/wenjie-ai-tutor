export const lessons=rows.map(([grade,title,problem,steps])=>({grade,title,problem,steps}));
export const clean=s=>String(s).normalize('NFKC').toLowerCase().replace(/[\s。！？?！]/g,'').replace(/[−–]/g,'-');
export function matches(reply,answers){
 const value=clean(reply).replace(/^(答案是|等于|是|x=)/,'').replace(/(平方厘米|千米|小时|厘米|米|元|个|支)$/,'');
 return answers.split('|').some(a=>clean(a)===clean(reply)||clean(a)===value || (/^[+-]?\d+(\.\d+)?$/.test(value)&&/^-?\d+$/.test(a)&&Number(value)===Number(a)));
}
export function lookup(problem){
 const known=lessons.find(l=>clean(l.problem)===clean(problem));
 if(known)return known;
 const eq=clean(problem).replace(/^(?:解方程|求解)[:：]?/,'').replace(/[.。]$/,'');
 if(eq==='3x+5=20')return lessons[6];
 const m=eq.match(/^(\d{1,3})x([+-]\d{1,4})=(-?\d{1,5})$/);
 if(!m)return null;
 const a=Number(m[1]), b=Number(m[2]), c=Number(m[3]);
 if(a<1||b===0||!Number.isInteger((c-b)/a))return null;
 return {grade:7,title:'保持等式平衡',problem,steps:[
 ['要抵消左边的 '+m[2]+'，两边同时加上几？',String(-b),'找一个与常数互为相反数的数。','加完以后，左边的常数应当等于零。'],
 ['做同样的运算后，右边等于几？',String(c-b),'在原式右边加上刚才的数。','注意这个数的正负号。'],
 ['现在两边同时除以系数，x 等于几？',String((c-b)/a),'几个相同的 x 合起来是右边的数？','把右边的数平均分给这些 x。']
 ]};
}
